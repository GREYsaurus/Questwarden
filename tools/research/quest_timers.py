# QuestieDB has no time limit. CMaNGOS keeps it per quest in quest_template.LimitTime (seconds; 0 = not timed).
# Only quests in the target's bundled quest data are written. The add-on warns before you accept one of these,
# shows the time left once the quest is in your log (read from the game, not from this table) and routes its
# turn-in first.
#
# Usage: python tools/research/quest_timers.py <Target> <Full_DB .sql.gz> <repository> <commit>
# Writes targets/<Target>/addon/Database/QuestTimers.lua.
import gzip
import os
import re
import sys

TARGET, SRC, REPO, COMMIT = sys.argv[1:5]
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))


def values(s, i):
    """Yield each tuple of an INSERT ... VALUES (...),(...); starting at s[i] == '('."""
    n = len(s)
    while i < n and s[i] == "(":
        row, i = [], i + 1
        while True:
            if s[i] == "'":
                j, out = i + 1, []
                while s[j] != "'":
                    if s[j] == "\\":
                        out.append(s[j + 1])
                        j += 2
                    elif s[j:j + 2] == "''":
                        out.append("'")
                        j += 2
                    else:
                        out.append(s[j])
                        j += 1
                row.append("".join(out))
                i = j + 1
            else:
                m = re.compile(r"[^,)]*").match(s, i)
                v = m.group(0).strip()
                row.append(None if v == "NULL" else v)
                i = m.end()
            if s[i] == ",":
                i += 1
                continue
            i += 1  # )
            break
        yield row
        while i < n and s[i] in ",\r\n\t ":
            i += 1


sql = gzip.open(SRC, "rt", encoding="utf-8", errors="replace").read()
create = re.search(r"CREATE TABLE `quest_template` \((.*?)\n\)", sql, re.S).group(1)
cols = re.findall(r"^\s*`(\w+)`", create, re.M)
ENTRY, LIMIT, TITLE = cols.index("entry"), cols.index("LimitTime"), cols.index("Title")

timed = {}
for m in re.finditer(r"INSERT INTO `quest_template` (?:\([^)]*\) )?VALUES\s*", sql):
    for row in values(sql, m.end()):
        if len(row) != len(cols):
            raise SystemExit("quest_template row with %d fields, expected %d" % (len(row), len(cols)))
        limit = int(row[LIMIT] or 0)
        if limit > 0:
            timed[int(row[ENTRY])] = (limit, row[TITLE] or "")

bundled = set(int(x) for x in re.findall(r"^Q\[(\d+)\]=", open(os.path.join(ROOT, "targets", TARGET, "addon", "Database", "Questie", "Quests.lua"), encoding="utf-8").read(), re.M))
keep = sorted(q for q in timed if q in bundled)

out = [
    "-- Questwarden - time limits of timed quests for " + TARGET,
    "-- Copyright (C) 2026 GREYsaurus (https://github.com/GREYsaurus)",
    "-- SPDX-License-Identifier: GPL-3.0-only",
    "-- GENERATED by tools/research/quest_timers.py from the CMaNGOS world database, quest_template.LimitTime",
    "-- (" + REPO + ", commit " + COMMIT + ", GPL-3.0). Only quests in the bundled quest data.",
    "-- [quest id] = seconds allowed after accepting.",
    "local _, ns = ...",
    "",
    "ns.QuestTimers = {",
]
for q in keep:
    limit, title = timed[q]
    out.append("    [%d] = %d, -- %s" % (q, limit, title.replace("\n", " ")))
out += ["}", ""]
dest = os.path.join(ROOT, "targets", TARGET, "addon", "Database", "QuestTimers.lua")
open(dest, "w", encoding="utf-8", newline="\n").write("\n".join(out))
print("%s: %d timed quests in the source, %d in the bundled data -> %s" % (TARGET, len(timed), len(keep), os.path.relpath(dest, ROOT)))
