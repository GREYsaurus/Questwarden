# Add saved-progress maps (Guides/Layouts.lua) for guides whose compiled steps were reordered.
# Copyright (C) 2026 GREYsaurus (https://github.com/GREYsaurus)
# SPDX-License-Identifier: GPL-3.0-only
#
# Saved progress is stored by step index (Core/SavedVars.lua ns:ApplyLayout). After a reorder, compare each
# compiled guide with the same file at a git revision (default HEAD, the last release): steps are matched by
# their compiled text (in order, for repeated lines), and every step whose index changed gets an entry
# old -> new in a new layout. A guide whose steps were added or removed is reported and left alone (the map
# would be incomplete); only pure reorders are mapped.
#
# Usage: python tools/research/layout_map.py <Target> [<rev>] [--dry-run]
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
a = [x for x in sys.argv[1:] if not x.startswith("--")]
TARGET, REV = a[0], (a[1] if len(a) > 1 else "HEAD")
DRY = "--dry-run" in sys.argv
CDIR = "targets/%s/addon/Guides/Compiled" % TARGET
LAYOUTS = os.path.join(ROOT, "targets", TARGET, "addon", "Guides", "Layouts.lua")
STEP_RE = re.compile(r'^    \{"\w+".*\},\s*$', re.M)


# Fields the compiler derives from step positions (kill packs, item-start kill steps) change with any reorder.
DERIVED_RE = re.compile(r",(pack=\d+|via=\{[\d,]*\})")


def guide(text):
    m = re.search(r'id="([^"]+)", name=', text)
    return (m.group(1), [DERIVED_RE.sub("", s.strip()) for s in STEP_RE.findall(text)]) if m else (None, [])


def mapping(old, new):
    pos = {}
    for i, s in enumerate(new):
        pos.setdefault(s, []).append(i)
    m = {}
    for i, s in enumerate(old):
        if not pos.get(s):
            return None
        j = pos[s].pop(0)
        if j != i:
            m[i + 1] = j + 1
    return m


maps = {}
for fn in sorted(os.listdir(os.path.join(ROOT, CDIR))):
    if not fn.endswith(".lua") or fn == "Routes.lua":
        continue
    new = open(os.path.join(ROOT, CDIR, fn), encoding="utf-8").read()
    old = subprocess.run(["git", "show", "%s:%s/%s" % (REV, CDIR, fn)], cwd=ROOT, capture_output=True,
                         encoding="utf-8").stdout
    gid, ns = guide(new)
    _, os_ = guide(old)
    if not gid or not os_ or ns == os_:
        continue
    if sorted(ns) != sorted(os_):
        print("%s: steps added or removed (%d -> %d); not mapped" % (gid, len(os_), len(ns)))
        continue
    m = mapping(os_, ns)
    maps[gid] = m
    print("%s: %d step(s) change index" % (gid, len(m)))

if maps and not DRY:
    raw = open(LAYOUTS, "rb").read().decode("utf-8")
    nl = "\r\n" if "\r\n" in raw else "\n"
    text = raw.replace("\r\n", "\n")
    rev = subprocess.run(["git", "rev-parse", "--short", REV], cwd=ROOT, capture_output=True, encoding="utf-8").stdout.strip()
    if re.search(r"^ns\.GuideLayouts = \{\}$", text, re.M):
        text = re.sub(r"^ns\.GuideLayouts = \{\}$", "ns.GuideLayouts = {\n}", text, flags=re.M)
        text = text.replace(": EMPTY until a released guide's steps are reordered.", ".")
        text = text.replace("-- Generated from the guide history; a new add-on starts with none.",
                            "-- GENERATED by tools/research/layout_map.py from the guide history. For each guide whose steps were\n"
                            "-- reordered: its layout number and, per change, a map old step index -> new step index.\n"
                            "-- ns:ApplyLayout (Core/SavedVars.lua) walks the maps from the layout a character saved with.")
    for gid, m in sorted(maps.items()):
        body = "{" + ",".join("[%d]=%d" % kv for kv in sorted(m.items())) + "}"
        line = re.search(r"^    %s = \{ layout = (\d+), maps = \{ (.*) \} \},(.*)$" % re.escape(gid), text, re.M)
        if line:
            v = int(line.group(1)) + 1
            note = (line.group(3) + ";") if line.group(3).strip() else " --"
            new = "    %s = { layout = %d, maps = { %s, [%d] = %s } },%s %s->now: reordered" % (
                gid, v, line.group(2), v, body, note, rev)
            text = text[:line.start()] + new + text[line.end():]
        else:
            entry = "    %s = { layout = 2, maps = { [2] = %s } }, -- %s->now: reordered\n" % (gid, body, rev)
            # Keep the table sorted by guide id.
            rows = list(re.finditer(r"^    (\w+) = \{ layout", text, re.M))
            after = [r for r in rows if r.group(1) > gid]
            at = after[0].start() if after else text.index("\n}", text.index("ns.GuideLayouts = {")) + 1
            text = text[:at] + entry + text[at:]
    open(LAYOUTS, "wb").write(text.replace("\n", nl).encode("utf-8"))
    print("wrote %s (%d guide(s))" % (os.path.relpath(LAYOUTS, ROOT), len(maps)))
