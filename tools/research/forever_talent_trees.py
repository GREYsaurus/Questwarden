"""Questwarden - writes targets/Forever/addon/Talents/Data/TalentTrees.lua from the researched Forever trees.

Input: tools/research/forever_talents.json (tools/research/forever_talents.py: tree, name, ranks, row, column,
prerequisite and icon per talent, from an online calculator, v=0) plus the Forever client tables in
.cache/upstream/db2/<build>/ (Talent, TalentTab, SpellName, Spell) for ids:
- tabs: the class's TalentTab rows in OrderIndex order (id, background, icon);
- talent id and per-rank spells: the client's own talent of the same name in that class, when its rank count
  is the same; otherwise per-rank spells are looked up by name and "Rank N" in the client spell tables, and
  only used when each rank has exactly one candidate (preferring spells Classic Era does not have). A talent
  with no client talent gets an internal id from 900001 up (it is only a key inside the add-on), and one
  whose spells cannot be told apart gets none: the talent window then shows its icon file instead.

Usage: python -I tools/research/forever_talent_trees.py
"""
import csv
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
TARGET = json.load(open(os.path.join(ROOT, "targets", "Forever", "target.json"), encoding="utf-8"))
BUILD = TARGET["clientTables"]["build"]
DB2 = os.path.join(ROOT, ".cache", "upstream", "db2", BUILD)
CLASSIC_DB2 = os.path.join(ROOT, ".cache", "upstream", "db2",
                           json.load(open(os.path.join(ROOT, "targets", "ClassicEra", "target.json"), encoding="utf-8"))["clientTables"]["build"])
RESEARCH = os.path.join(ROOT, "tools", "research", "forever_talents.json")
OUT = os.path.join(ROOT, "targets", "Forever", "addon", "Talents", "Data", "TalentTrees.lua")
CLASS_ID = {"WARRIOR": 1, "PALADIN": 2, "HUNTER": 3, "ROGUE": 4, "PRIEST": 5, "SHAMAN": 7, "MAGE": 8, "WARLOCK": 9, "DRUID": 11}


def rows(folder, table):
    with open(os.path.join(folder, table + ".csv"), encoding="utf-8") as fh:
        return list(csv.DictReader(fh))


def num(r, k):
    try:
        return int(r.get(k) or 0)
    except ValueError:
        return 0


def lua_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    research = json.load(open(RESEARCH, encoding="utf-8"))
    names = {num(r, "ID"): r["Name_lang"] for r in rows(DB2, "SpellName")}
    subtext = {num(r, "ID"): r.get("NameSubtext_lang") or "" for r in rows(DB2, "Spell")}
    classic_ids = {num(r, "ID") for r in rows(CLASSIC_DB2, "SpellName")}
    by_name = {}
    for sid, n in names.items():
        by_name.setdefault(n, []).append(sid)
    tabs = rows(DB2, "TalentTab")
    base = {}  # (class, name) -> client talent
    for r in rows(DB2, "Talent"):
        spells = [num(r, "SpellRank_%d" % k) for k in range(9)]
        spells = [s for s in spells if s > 0]
        if not spells:
            continue
        tab = next((t for t in tabs if num(t, "ID") == num(r, "TabID")), None)
        if not tab:
            continue
        for cls, cid in CLASS_ID.items():
            if num(tab, "ClassMask") == 1 << (cid - 1):
                base[(cls, names.get(spells[0], ""))] = {"id": num(r, "ID"), "spells": spells}

    def lookup(name, ranks):
        out = []
        for k in range(1, ranks + 1):
            cands = [s for s in by_name.get(name, []) if subtext.get(s, "") in (("Rank %d" % k),) + (("",) if ranks == 1 else ())]
            new = [s for s in cands if s not in classic_ids]
            pick = new if new else cands
            if len(pick) != 1:
                return []
            out.append(pick[0])
        return out

    next_id = 900001
    stats = {"client": 0, "spells": 0, "nospells": 0}
    lines = [
        "-- Questwarden - talent trees for World of Warcraft: Forever (src = research, v = 0)",
        "-- GENERATED by tools/research/forever_talent_trees.py. DO NOT EDIT BY HAND.",
        "-- Trees, rows, columns, ranks and prerequisites: " + research["_source"] + ", read " + research["_read"] + ".",
        "-- Forever's trees come from server hotfixes, not the client's base tables (docs/FOREVER_PLAN.md); UNVERIFIED until",
        "-- checked in the game. Ids: the client's talent of the same name where there is one, else an internal id from",
        "-- 900001 (a key inside the add-on only). spells = the client's spell per rank where it could be told apart, else",
        "-- empty; iconFile = the talent's icon file name, for the talent window when there is no spell.",
        "-- Fields per talent: id, name, tier (1-7), column (1-4), ranks, spells{per rank}, iconFile, prereq{talentId, rank} or nil",
        "local _, ns = ...",
        "ns.TalentTrees = ns.TalentTrees or {}",
        'ns.TalentTrees.build = "' + BUILD + '+research"',
        "local T = ns.TalentTrees",
    ]
    warnings = []
    for cls in sorted(research["classes"]):
        trees = research["classes"][cls]
        mask = 1 << (CLASS_ID[cls] - 1)
        client_tabs = sorted([t for t in tabs if num(t, "ClassMask") == mask], key=lambda t: num(t, "OrderIndex"))
        lines.append("T.%s = {" % cls)
        for i, tree in enumerate(trees):
            tab = client_tabs[i] if i < len(client_tabs) else None
            if not tab or tab["Name_lang"].split()[0] != tree["name"].split()[0]:
                warnings.append("%s tree %d: calculator says %s, client tab %s" % (cls, i + 1, tree["name"], tab and tab["Name_lang"]))
            ids = {}
            for t in tree["talents"]:
                b = base.get((cls, t["name"]))
                if b and len(b["spells"]) == t["ranks"]:
                    t["_id"], t["_spells"] = b["id"], b["spells"]
                    stats["client"] += 1
                else:
                    t["_id"] = b["id"] if b else next_id
                    if not b:
                        next_id += 1
                    t["_spells"] = lookup(t["name"], t["ranks"])
                stats["spells" if t["_spells"] else "nospells"] += 1
                ids[t["name"]] = t
            lines.append("  {id=%d,name=%s,background=%s,icon=%d,talents={" % (
                num(tab, "ID") if tab else 0, lua_str(tree["name"]), lua_str(tab["BackgroundFile"] if tab else ""), num(tab, "SpellIconID") if tab else 0))
            for t in sorted(tree["talents"], key=lambda x: (x["tier"], x["column"])):
                s = "    {id=%d,name=%s,tier=%d,column=%d,ranks=%d,spells={%s}" % (
                    t["_id"], lua_str(t["name"]), t["tier"], t["column"], t["ranks"], ",".join(str(x) for x in t["_spells"]))
                if t.get("icon"):
                    s += ",iconFile=" + lua_str(t["icon"])
                if t.get("requires"):
                    p = ids.get(t["requires"])
                    if p:
                        s += ",prereq={%d,%d}" % (p["_id"], p["ranks"])
                    else:
                        warnings.append("%s %s: prerequisite %s is not in its tree" % (cls, t["name"], t["requires"]))
                lines.append(s + "},")
            lines.append("  }},")
        lines.append("}")
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines) + "\n")
    print("talents: %d with the client's id and spells, %d with spells found by name, %d without spells; internal ids: %d" % (
        stats["client"], stats["spells"] - stats["client"], stats["nospells"], next_id - 900001))
    for w in warnings:
        print("WARNING: " + w)


if __name__ == "__main__":
    main()
