# Cross-check our generated data against another guide add-on's data files (docs/DATA_POLICY.md, "The cross-check
# process"). Reads the reference files from a folder OUTSIDE the repository and writes only a comparison report,
# docs/generated/CROSSCHECK.md. Nothing it reads from the reference files goes into the add-on: each difference is
# checked against our own sources or in game, and never filled with their value.
# Copyright (C) 2026 GREYsaurus (https://github.com/GREYsaurus)
# SPDX-License-Identifier: GPL-3.0-only
#
# Compared (files the folder lacks are skipped):
#   SpiritHealerDB.lua  graveyard positions          vs Database/Questie/SpiritHealers.lua (40-yard match)
#   flightData.lua      flight nodes per faction      vs Database/Flights.lua (node ids are the client's)
#   rares.lua           rare names per zone (enUS)    vs rares in Database/Questie/Npcs.lua and QuestieDB
#   dangerousMobs.lua   mob levels and rank           vs QuestieDB (facts only: their notes, movement and choice of
#                                                       mobs are not used)
#   spells.lua          class spell ids and levels    vs Classes/TrainingData.lua and Classes/PetData.lua
# Names in the report come from our data or the client tables, not from the reference files' labels.
# Usage: python tools/research/crosscheck.py <Target> <reference folder>   (or tools/build.ps1 crosscheck -Reference <folder>)
import csv
import math
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from qdb import ROOT, Target, arr, hsh, parse_lua  # noqa: E402

T = Target(sys.argv[1] if len(sys.argv) > 1 else "ClassicEra")
REF = os.path.abspath(sys.argv[2]) if len(sys.argv) > 2 else None
if not REF or not os.path.isdir(REF):
    sys.exit("usage: crosscheck.py <Target> <reference folder outside the repository>")
if os.path.commonpath([REF, ROOT]) == ROOT:
    sys.exit("the reference folder must be outside the repository (docs/DATA_POLICY.md)")
OUT = os.path.join(ROOT, "docs", "generated", "CROSSCHECK.md")
DB2 = os.path.join(ROOT, ".cache", "upstream", "db2", T.info["clientTables"]["build"])
MATCH_YARDS = 40.0
LIST_MAX = 40  # entries listed per line before "... and N more"
RANK = {0: "normal", 1: "elite", 2: "rare elite", 3: "boss", 4: "rare"}


def ref(name):
    p = os.path.join(REF, name)
    return open(p, encoding="utf-8", errors="replace").read() if os.path.exists(p) else None


def ours(rel):
    return open(os.path.join(T.dir, "addon", rel), encoding="utf-8").read()


def more(items):
    items = list(items)
    if not items:
        return "none"
    s = ", ".join(items[:LIST_MAX])
    return s + (" ... and %d more" % (len(items) - LIST_MAX) if len(items) > LIST_MAX else "")


# ---------------------------------------------------------------- our side: zones and map boxes
zl = ours("Database/Questie/Zones.lua")
UI = {int(a): int(b) for a, b in re.findall(r"^\[(\d+)\]=(\d+),$", zl.split("Z.names")[0], re.M)}
ZNAME = {int(a): b for a, b in re.findall(r'^\[(\d+)\]="(.*)",$', zl.split("Z.names")[1].split("Z.parent")[0], re.M)}
ZBYNAME = {}
for z, n in sorted(ZNAME.items()):
    if z in UI:
        ZBYNAME.setdefault(n, z)
BOX = {}  # zone -> (continent, minX, minY, maxX, maxY)
zone_of_ui = {}
for z, u in UI.items():
    zone_of_ui.setdefault(u, z)
for r in csv.DictReader(open(os.path.join(DB2, "UiMapAssignment.csv"), encoding="utf-8")):
    if (r["UiMin_0"], r["UiMin_1"], r["UiMax_0"], r["UiMax_1"]) != ("0", "0", "1", "1"):
        continue
    z = zone_of_ui.get(int(r["UiMapID"]))
    if z is not None and z not in BOX:
        BOX[z] = (int(r["MapID"]), float(r["Region_0"]), float(r["Region_1"]), float(r["Region_3"]), float(r["Region_4"]))


ZONES_KNOWN = {ZNAME[z] for z in BOX if z in ZNAME}  # zones with a map on this client


def to_world(z, x, y):
    c, x0, y0, x1, y1 = BOX[z]
    return c, x1 - y / 100 * (x1 - x0), y1 - x / 100 * (y1 - y0)


def zone_at(c, wx, wy):
    best = None
    for z, (bc, x0, y0, x1, y1) in BOX.items():
        if bc == c and x0 <= wx <= x1 and y0 <= wy <= y1:
            a = (x1 - x0) * (y1 - y0)
            if best is None or a < best[0]:
                best = (a, z)
    return ZNAME.get(best[1], "?") if best else "outside every zone map"


report = ["# Cross-check report", "",
          "GENERATED by `tools/build.ps1 crosscheck` (`tools/research/crosscheck.py`) for target **%s**. "
          "Our data compared with a reference add-on's data files, read from a folder outside the repository. "
          "Nothing from them is used in the add-on (docs/DATA_POLICY.md): each difference is resolved from our own "
          "sources or added to the in-game check list in docs/DATA_GAPS.md." % T.name, ""]
summary = []

# ---------------------------------------------------------------- spirit healers
txt = ref("SpiritHealerDB.lua")
if txt is not None:
    theirs, cont = [], None
    for line in txt.splitlines():
        m = re.match(r"^\s*\[(\d+)\]\s*=\s*\{\s*$", line)
        if m:
            cont = int(m.group(1))
        m = re.search(r"wx\s*=\s*([-\d.]+),\s*wy\s*=\s*([-\d.]+)", line)
        if m and cont in (0, 1):  # Eastern Kingdoms and Kalimdor; battlegrounds are left out
            theirs.append((cont, float(m.group(1)), float(m.group(2))))
    mine = []  # (zone, continent, wx, wy)
    sh = re.search(r"spiritHealers = (\{.*\})", ours("Database/Questie/SpiritHealers.lua"), re.S)
    if sh:
        t = parse_lua(sh.group(1))
        for z, pts in list(hsh(t).items()) + [(i + 1, v) for i, v in enumerate(arr(t))]:
            if z in BOX:
                for p in arr(pts):
                    p = arr(p)
                    mine.append((z,) + to_world(z, p[0], p[1]))
    t_only = [a for a in theirs if not any(b[1] == a[0] and math.hypot(b[2] - a[1], b[3] - a[2]) <= MATCH_YARDS for b in mine)]
    o_only = [b for b in mine if not any(a[0] == b[1] and math.hypot(b[2] - a[1], b[3] - a[2]) <= MATCH_YARDS for a in theirs)]
    report += ["## Spirit healers", "",
               "Ours: %d positions (QuestieDB). Reference: %d on Eastern Kingdoms and Kalimdor. Matched within %d yards: %d of ours." %
               (len(mine), len(theirs), MATCH_YARDS, len(mine) - len(o_only)), "",
               "- **Only in the reference (%d)**, by our zone maps, world coordinates: %s" % (len(t_only), more(
                   "%s (%.0f, %.0f)" % (zone_at(c, wx, wy), wx, wy) for c, wx, wy in t_only)),
               "- **Only in ours (%d):** %s" % (len(o_only), more(
                   "%s (%.0f, %.0f)" % (ZNAME.get(z, z), wx, wy) for z, c, wx, wy in o_only)), ""]
    summary.append("Spirit healers: %d only in the reference, %d only in ours" % (len(t_only), len(o_only)))

# ---------------------------------------------------------------- flight nodes
txt = ref("flightData.lua")
if txt is not None:
    theirs, fac, timed = {"Alliance": set(), "Horde": set()}, None, 0
    for line in txt.splitlines():
        m = re.match(r'^ {4}\["(Alliance|Horde)"\]', line)
        if m:
            fac = m.group(1)
        m = re.match(r"^ {8}\[(\d+)\]\s*=\s*\{", line)
        if m and fac:
            theirs[fac].add(int(m.group(1)))
        if re.match(r"^ {12}\[\d+\]\s*=\s*\d+", line):
            timed += 1
    client = {int(r["ID"]): r["Name_lang"] for r in csv.DictReader(open(os.path.join(DB2, "TaxiNodes.csv"), encoding="utf-8"))}
    nodes = {int(a): f for a, f in re.findall(r'^N\[(\d+)\]=\{.*?faction="(\w+)"', ours("Database/Flights.lua"), re.M)}
    report += ["## Flight nodes", "",
               "Ours: %d nodes from the client's TaxiNodes/TaxiPath. The reference also holds %d timed flights; we have "
               "no flight times (they are measured in game) and do not use theirs. Node names below are the client's." %
               (len(nodes), timed), ""]
    tot_t = tot_o = 0
    for f, c in (("Alliance", "A"), ("Horde", "H")):
        mine = {n for n, fs in nodes.items() if c in fs}
        t_only, o_only = theirs[f] - mine, mine - theirs[f]
        tot_t += len(t_only)
        tot_o += len(o_only)
        report.append("- **%s:** ours %d, reference %d. Only in the reference: %s. Only in ours: %s." % (
            f, len(mine), len(theirs[f]), more("%d %s" % (n, client.get(n, "?")) for n in sorted(t_only)),
            more("%d %s" % (n, client.get(n, "?")) for n in sorted(o_only))))
    report.append("")
    summary.append("Flight nodes: %d only in the reference, %d only in ours" % (tot_t, tot_o))

# ---------------------------------------------------------------- rares
txt = ref("rares.lua")
if txt is not None:
    en = re.split(r"elseif locale ==", txt)[0]
    theirs = {}
    for m in re.finditer(r'\["([^"]+)"\]\s*=\s*\{([^}]*)\}', en):
        theirs[m.group(1)] = set(re.findall(r'"([^"]+)"', m.group(2)))
    N = T._bundled("Npcs.lua", "N")
    mine = {}  # our zone name -> bundled hostile rare names
    for nid, r in N.items():
        if r[3] in (2, 4) and r[6] != "AH":  # rares friendly to one faction are kept for the other
            # zone 1 (Dun Morogh) is written as the table's array part: {{x,y},...} instead of [1]=...
            for z in list(hsh(r[5])) + list(range(1, len(arr(r[5])) + 1)):
                mine.setdefault(ZNAME.get(z, str(z)), set()).add(r[0])
    every = {}  # QuestieDB name -> [ranks, zone names, friendly marks of its rare records with spawns]
    for nid, r in T.N.items():
        e = every.setdefault(r[0], [set(), set(), set()])
        e[0].add(r[3] or 0)
        e[1].update(ZNAME.get(z, str(z)) for z in hsh(r[5]))
        # Spawns at -1,-1 are QuestieDB's mark for "inside an instance": no map position.
        placed = any((arr(p) or [-1])[0] >= 0 for pts in hsh(r[5]).values() for p in arr(pts))
        if (r[3] or 0) in (2, 4) and placed:
            e[2].add(r[6] or "-")

    def in_zone(zone):
        # Instance zones are named "Blackrock Depths - Dungeon -- ..." in our data.
        out = set()
        for z, names in mine.items():
            if z == zone or z.startswith(zone + " - "):
                out |= names
        return out
    t_missing, t_rank, t_friendly, t_nospawn, t_zone = [], [], [], [], []
    for zone, names in sorted(theirs.items()):
        for n in sorted(names - in_zone(zone)):
            e = every.get(n)
            if not e:
                t_missing.append("%s (%s)" % (n, zone))
            elif not (e[0] & {2, 4}):
                t_rank.append("%s (%s: %s)" % (n, zone, "/".join(RANK[x] for x in sorted(e[0]))))
            elif e[2] and "-" not in e[2]:
                t_friendly.append("%s (%s; marked friendly to %s)" % (n, zone, "/".join(sorted(e[2]))))
            elif not e[2]:
                t_nospawn.append("%s (%s)" % (n, zone))
            else:
                t_zone.append("%s (%s; ours: %s)" % (n, zone, ", ".join(sorted(e[1]))))
    their_all = set().union(*theirs.values()) if theirs else set()
    mine_all = {n for s in mine.values() for n in s}
    o_only = sorted(mine_all - their_all)
    report += ["## Rares", "",
               "Ours: %d hostile rares and rare elites with spawns (QuestieDB). Reference: %d names in %d zones (enUS list)." %
               (len(mine_all), len(their_all), len(theirs)), "",
               "- **Not in QuestieDB at all (%d):** %s" % (len(t_missing), more(t_missing)),
               "- **QuestieDB does not rank them rare (%d):** %s" % (len(t_rank), more(t_rank)),
               "- **QuestieDB rares we leave out because QuestieDB marks them friendly (%d):** %s" % (len(t_friendly), more(t_friendly)),
               "- **QuestieDB rares without a map position** (no spawn data, or inside an instance) **(%d):** %s" % (len(t_nospawn), more(t_nospawn)),
               "- **We place them in another zone (%d):** %s" % (len(t_zone), more(t_zone)),
               "- **Our rares the reference does not list (%d):** %s" % (len(o_only), more(o_only)), ""]
    summary.append("Rares: %d unknown to QuestieDB, %d ranked differently, %d marked friendly, %d without spawns, "
                   "%d in other zones, %d only in ours" %
                   (len(t_missing), len(t_rank), len(t_friendly), len(t_nospawn), len(t_zone), len(o_only)))

# ---------------------------------------------------------------- dangerous mobs: levels and rank only
txt = ref("dangerousMobs.lua")
if txt is not None:
    entries, zone, mob, cur = [], None, None, None
    for line in txt.splitlines():
        m = re.match(r'^    \["([^"]+)"\]\s*=\s*\{', line)
        if m:
            zone = m.group(1)
            continue
        m = re.match(r'^      \["([^"]+)"\]\s*=\s*\{', line)
        if m:
            mob = re.sub(r"\s*<[^>]*>", "", m.group(1)).strip()
            continue
        m = re.match(r'^\s*(MinLevel|MaxLevel|Classification)\s*=\s*"?([^",]*)"?', line)
        if m:
            if m.group(1) == "MinLevel":
                cur = dict(zone=zone, mob=mob)
                entries.append(cur)
            if cur is not None:
                cur[m.group(1)] = m.group(2).strip()
    cls = {"Normal": {0}, "Elite": {1}, "Rare Elite": {2}, "Rare": {4}, "Boss": {3}}
    by_name = {}
    for nid, r in T.N.items():
        by_name.setdefault(r[0], []).append(r)
    missing, lvl, rnk, seen, other = [], [], [], set(), 0
    for e in entries:
        if e["zone"] not in ZONES_KNOWN:  # the file also covers other game versions' zones
            other += 1
            continue
        key = (e["mob"], e["zone"])
        if key in seen:
            continue
        seen.add(key)
        cands = by_name.get(e["mob"], [])
        if not cands:
            missing.append("%s (%s)" % key)
            continue
        z = ZBYNAME.get(e["zone"])
        here = [r for r in cands if z in hsh(r[5])] or cands
        try:
            lo, hi = int(e.get("MinLevel", 0)), int(e.get("MaxLevel", 0))
        except ValueError:
            lo = hi = 0
        if lo and not any((r[1] or 0) <= lo and hi <= (r[2] or 0) for r in here):
            lvl.append("%s (%s): reference %d-%d, QuestieDB %s" % (key + (lo, hi, "/".join(sorted({"%s-%s" % (r[1], r[2]) for r in here})))))
        want = cls.get(e.get("Classification"))
        if want and not any((r[3] or 0) in want for r in here):
            rnk.append("%s (%s): reference %s, QuestieDB %s" % (key + (e["Classification"].lower(), "/".join(sorted({RANK[r[3] or 0] for r in here})))))
    report += ["## Dangerous mobs: levels and rank", "",
               "Facts only: for each mob the reference lists, whether QuestieDB knows it and agrees on its level range and "
               "rank. Their notes, movement and choice of mobs are not used; our own danger rules are in "
               "`tools/research/danger_report.py`. %d mobs checked; %d entries in zones this target does not have were skipped." %
               (len(seen), other), "",
               "- **Not in QuestieDB by that name (%d):** %s" % (len(missing), more(missing)),
               "- **Level range differs (%d):** %s" % (len(lvl), more(lvl)),
               "- **Rank differs (%d):** %s" % (len(rnk), more(rnk)), ""]
    summary.append("Dangerous mobs: %d unknown to QuestieDB, %d level differences, %d rank differences" % (len(missing), len(lvl), len(rnk)))

# ---------------------------------------------------------------- class spells
txt = ref("spells.lua")
if txt is not None:
    theirs, cl, lv = {}, None, None
    for line in txt.splitlines():
        m = re.match(r'^s\["([A-Z]+)"\]\s*=\s*\{', line)
        if m:
            cl = m.group(1)
            continue
        if re.match(r'^(s\["|addon\.)', line):
            cl = None
        if not cl:
            continue
        m = re.match(r"^\s*\[(\d+)\]\s*=\s*\{(.*)$", line)
        if m:
            lv = int(m.group(1))
            line = m.group(2)
        for sid in re.findall(r"(?<![\w.])(\d{2,6})(?![\w.])", line.split("--")[0]):
            theirs.setdefault(cl, {})[int(sid)] = lv
    names = {int(r["ID"]): r["Name_lang"] for r in csv.DictReader(open(os.path.join(DB2, "SpellName.csv"), encoding="utf-8"))}
    mine, cur = {}, None
    for line in ours("Classes/TrainingData.lua").splitlines():
        m = re.match(r"^    ([A-Z]+) = \{", line)
        if m:
            cur = m.group(1)
        m = re.match(r"^      \{(\d+),(\d+),", line)
        if m and cur:
            mine.setdefault(cur, {})[int(m.group(1))] = int(m.group(2))
    pet = {int(x) for x in re.findall(r"\d+", ours("Classes/PetData.lua").split("ns.PetData", 1)[1])}
    # Hunter-side Beast Training spells (Growl 14924 ...) teach a pet spell (Growl 14918); the client's learn-spell
    # effect (Effect 36) links them, so a teaching spell counts as present when the pet spell it teaches is ours.
    for r in csv.DictReader(open(os.path.join(DB2, "SpellEffect.csv"), encoding="utf-8")):
        if r["Effect"] == "36" and int(r["EffectTriggerSpell"] or 0) in pet:
            pet.add(int(r["SpellID"]))
    notours, earlier, petn, later = [], [], 0, 0
    for c in sorted(theirs):
        for sid, l in sorted(theirs[c].items(), key=lambda x: (x[1] or 0, x[0])):
            if sid not in mine.get(c, {}):
                if sid in pet:
                    petn += 1
                else:
                    notours.append("%s %d %s (level %s)" % (c, sid, names.get(sid, "?"), l))
            elif l and l < mine[c][sid]:
                earlier.append("%s %d %s: reference %d, ours %d" % (c, sid, names.get(sid, "?"), l, mine[c][sid]))
            elif l and l > mine[c][sid]:
                later += 1
    report += ["## Class trainer spells", "",
               "Spell ids the reference lists per class and level, compared with our trainer data from the client tables. "
               "Client tables beat a hand-made list; a spell missing from ours may be a quest spell, a talent rank or a "
               "spell our rules leave out (docs/TRAINER.md). %d spells checked." % sum(len(v) for v in theirs.values()), "",
               "- **Not in our trainer or pet data (%d):** %s" % (len(notours), more(notours)),
               "- **Listed earlier than our trainer level (%d)** (would mean our level is wrong): %s" % (len(earlier), more(earlier)),
               "- **Hunter pet skills** (in our pet data, directly or as the Beast Training spell that teaches the pet rank): %d." % petn,
               "- **Listed later than our trainer level:** %d. Not a disagreement: a list of when to train may wait." % later, ""]
    summary.append("Class spells: %d not in our trainer or pet data, %d listed earlier than our trainer level" % (len(notours), len(earlier)))

report[4:4] = ["## Summary", ""] + ["- " + s for s in summary] + [""]
with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
    fh.write("\n".join(report))
print("\n".join(summary))
print("wrote " + OUT)
