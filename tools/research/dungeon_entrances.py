# QuestieDB keeps, per instance area id: name, alternative area ids (wings, sub-areas), parent zone and the
# entrance points ({zone, x, y}, zone-map percent). Its base table is the Classic and TBC layout; the overrides
# below it apply from Wrath of the Lich King on and are not used here. Faction-dependent entries (battlegrounds)
# are not dungeons and are skipped.
#
# Only dungeons in the target's dungeon list (targets/<Target>/addon/Database/Dungeons.lua) are written, keyed by
# that list's name. A listed dungeon without an entry in the source gets none: the guide then has no entrance
# arrow for it and says so; no position is guessed.
#
# Usage: python tools/research/dungeon_entrances.py <Target> <path to dungeons.lua> <QuestieDB commit>
# Writes targets/<Target>/addon/Database/DungeonEntrances.lua.
import os
import re
import sys

TARGET, SRC, COMMIT = sys.argv[1], sys.argv[2], sys.argv[3]
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

src = open(SRC, encoding="utf-8").read()
base = src.split("if Expansions.Current", 1)[0]  # only the base (Classic/TBC) table
ENTRY = re.compile(r'^\s*\[(\d+)\]\s*=\s*\{"([^"]+)",\s*(nil|\{[\d,\s]*\}),\s*(\d+),\s*\{(.*)\}\},', re.M)
POINT = re.compile(r'\{\s*(\d+)\s*,\s*([\d.]+)\s*,\s*([\d.]+)\s*\}')

source = {}
for m in ENTRY.finditer(base):
    area, name, alts, _parent, pts = int(m.group(1)), m.group(2), m.group(3), m.group(4), m.group(5)
    if "isHorde" in pts:
        continue
    points = [(int(z), float(x), float(y)) for z, x, y in POINT.findall(pts)]
    areas = [area] + ([int(a) for a in re.findall(r"\d+", alts)] if alts != "nil" else [])
    rec = source.setdefault(name, {"areas": [], "points": []})
    for a in areas:
        if a not in rec["areas"]:
            rec["areas"].append(a)
    for p in points:
        if p not in rec["points"]:
            rec["points"].append(p)

listed = re.findall(r'name = "([^"]+)"', open(os.path.join(ROOT, "targets", TARGET, "addon", "Database", "Dungeons.lua"), encoding="utf-8").read())

def num(v):
    return ("%.2f" % v).rstrip("0").rstrip(".")

out = [
    "-- Questwarden - dungeon entrances for " + TARGET,
    "-- Copyright (C) 2026 GREYsaurus (https://github.com/GREYsaurus)",
    "-- SPDX-License-Identifier: GPL-3.0-only",
    "-- GENERATED by tools/research/dungeon_entrances.py from QuestieDB support/Zones/dungeons.lua (commit " + COMMIT + ",",
    "-- base Classic/TBC table). Upstream data keeps its upstream terms: see NOTICE.md and THIRD_PARTY_LICENSES.md.",
    "-- [dungeon list name] = { areas = { instance area ids }, points = { {zone, x, y}, ... } } (zone-map percent).",
    "local _, ns = ...",
    "",
    "ns.DungeonEntrances = {",
]
missing = []
for name in listed:
    rec = source.get(name)
    if not rec or not rec["points"]:
        missing.append(name)
        continue
    areas = ", ".join(str(a) for a in rec["areas"])
    pts = ", ".join("{ %d, %s, %s }" % (z, num(x), num(y)) for z, x, y in rec["points"])
    out.append('    ["%s"] = { areas = { %s }, points = { %s } },' % (name, areas, pts))
out.append("}")
if missing:
    out.append("-- No entrance in the source for: " + ", ".join(missing) + ".")
path = os.path.join(ROOT, "targets", TARGET, "addon", "Database", "DungeonEntrances.lua")
with open(path, "w", encoding="utf-8", newline="\n") as f:
    f.write("\n".join(out) + "\n")
print("%s: %d of %d dungeons with an entrance%s" % (TARGET, len(listed) - len(missing), len(listed),
      ("; none for " + ", ".join(missing)) if missing else ""))
