#
# Upstream keeps one Lua file per class and game: Classes/Vanilla/<Class>.lua (Classic Era 1.15.x) and
# Classes/TBC/<Class>.lua (TBC Classic 2.5.x); its TOC (Interface 20506, 11509) loads Classes\[Game]\<Class>.lua. Each
# file sets wt.SpellsByLevel = { [level] = { {id=, cost=, requiredIds=, requiredTalentId=, faction=, race(s)=, skills=}, ... } }.
# The files are run here, unchanged, with a stand-in for the add-on object (wt): FactionFilter and RaceFilter return their
# table as is (every faction's and race's entries are kept, with the restriction recorded), and AddOverriddenSpells is
# ignored (a display rule of the add-on). Pet abilities, Warlock tomes and weapon skills are not imported.
#
# Output (written, never edited by hand): targets/<Target>/addon/Classes/WhatsTrainingData.lua, and a comparison with the
# client-table spell list (Classes/TrainingData.lua) in docs/generated/<Target>/whatstraining-crosscheck.md.
#
# Usage: python -I tools/research/whatstraining_import.py <Target> <What's Training checkout> <commit>
import csv
import os
import re
import sys

import lupa.lua51 as lua51

TARGET, SRC, COMMIT = sys.argv[1], sys.argv[2], sys.argv[3]
GAME = {"ClassicEra": "Vanilla", "TBC": "TBC"}.get(TARGET)
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
CLASSES = ["DRUID", "HUNTER", "MAGE", "PALADIN", "PRIEST", "ROGUE", "SHAMAN", "WARLOCK", "WARRIOR"]
BUILD = {"ClassicEra": "1.15.9.70576", "TBC": "2.5.6.70577"}.get(TARGET)

out_lua = os.path.join(ROOT, "targets", TARGET, "addon", "Classes", "WhatsTrainingData.lua")
header = [
    "-- Questwarden - class trainer spell list and baseline prices from What's Training? (" + (GAME or "none") + " data)",
    "-- GENERATED by tools/research/whatstraining_import.py from https://github.com/fusionpit/WhatsTraining at commit",
    "-- " + COMMIT + (" (Classes/" + GAME + "/<Class>.lua)" if GAME else "") + ". DO NOT EDIT.",
    "-- That data is MIT licensed: Copyright (c) 2019 fusionpit (What's Training?); the licence text is in",
    "-- Classes/WhatsTraining_LICENSE.txt and THIRD_PARTY_LICENSES.md. Rows: [spellId] = { level, cost (copper, the",
    "-- trainer's base price), { required spell ids }, required talent spell id or 0, faction (\"Alliance\"/\"Horde\"/\"\"),",
    "-- { race tokens } or false, { {skill line, skill level} } or false }.",
    "local _, ns = ...",
    "",
]
if not GAME:
    with open(out_lua, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(header + ["ns.WhatsTrainingData = { classes = {} } -- no upstream data for this target", ""]))
    print(TARGET + ": no What's Training data for this target (empty file)")
    sys.exit(0)

# Numeric race ids (ChrRaces.ID) -> race tokens (ChrRaces.ClientFileString), from this build's client table.
races = {}
with open(os.path.join(ROOT, ".cache", "upstream", "db2", BUILD, "ChrRaces.csv"), encoding="utf-8") as f:
    for row in csv.DictReader(f):
        races[int(row["ID"])] = row["ClientFileString"]

STUB = """
local class = ...
local wt = { currentClass = class, playerFaction = "Alliance", playerRace = 1 }
function wt.FactionFilter(t) return t end
function wt.RaceFilter(t) return t end
function wt:AddOverriddenSpells() end
return wt
"""


def load_class(cls):
    rt = lua51.LuaRuntime(unpack_returned_tuples=True)
    wt = rt.execute(STUB, cls)
    path = os.path.join(SRC, "Classes", GAME, cls.capitalize() + ".lua")
    code = open(path, encoding="utf-8").read()
    chunk = rt.eval("function(code, wt) local f = assert(loadstring(code)) f('WhatsTraining', wt) end")
    chunk(code, wt)
    # Hunter pet abilities are taught to the pet (pet trainer / Beast Training), not by the class trainer: upstream
    # lists them in Classes/<Game>/HunterPets.lua (wt.PetAbilityIds); they are left out here.
    pet = set()
    pets = os.path.join(SRC, "Classes", GAME, "HunterPets.lua")
    if cls == "HUNTER" and os.path.exists(pets):
        chunk(open(pets, encoding="utf-8").read(), wt)
        pet = {int(k) for k in (wt.PetAbilityIds or {}).keys()}
    sbl = wt.SpellsByLevel
    rows = {}
    for level in sorted(sbl.keys()):
        for _, s in sbl[level].items():
            sid = s["id"]
            if sid is None or int(sid) in pet:
                continue
            req = [int(v) for _, v in (s["requiredIds"] or {}).items()] if s["requiredIds"] else []
            rlist = []
            if s["race"]:
                rlist.append(races[int(s["race"])])
            if s["races"]:
                rlist += [races[int(v)] for _, v in s["races"].items()]
            skills = []
            if s["skills"]:
                for _, sk in s["skills"].items():
                    skills.append((int(sk["skill"]), int(sk["level"])))
            rows[int(sid)] = (int(level), int(s["cost"] or 0), req, int(s["requiredTalentId"] or 0), s["faction"] or "", rlist, skills)
    return rows


def lua_list(v):
    return "{" + ",".join(str(x) for x in v) + "}"


def lua_strs(v):
    return "{" + ",".join('"' + x + '"' for x in v) + "}" if v else "false"


body = ["ns.WhatsTrainingData = {", '  source = { repository = "https://github.com/fusionpit/WhatsTraining", commit = "' + COMMIT
        + '", game = "' + GAME + '" },', "  classes = {"]
data = {}
for cls in CLASSES:
    rows = load_class(cls)
    data[cls] = rows
    body.append("    " + cls + " = {")
    for sid in sorted(rows, key=lambda i: (rows[i][0], i)):
        lvl, cost, req, tal, fac, rl, sk = rows[sid]
        skills = "{" + ",".join("{%d,%d}" % x for x in sk) + "}" if sk else "false"
        body.append("      [%d] = {%d,%d,%s,%d,\"%s\",%s,%s}," % (sid, lvl, cost, lua_list(req), tal, fac, lua_strs(rl), skills))
    body.append("    },")
body += ["  },", "}", ""]
with open(out_lua, "w", encoding="utf-8", newline="\n") as f:
    f.write("\n".join(header + body))

# Comparison with the client-table spell list ---------------------------------------------------------------------------
ours = {}
cur = None
for line in open(os.path.join(ROOT, "targets", TARGET, "addon", "Classes", "TrainingData.lua"), encoding="utf-8"):
    m = re.match(r"\s+([A-Z]+) = \{\s*$", line)
    if m:
        cur = m.group(1)
        ours[cur] = {}
        continue
    m = re.match(r"\s+\{(\d+),(\d+),(\d+),(\d+),\"([^\"]*)\",(\d+),(\d+)\},", line)
    if m and cur:
        ours[cur][int(m.group(1))] = (int(m.group(2)), m.group(5), int(m.group(6)))
notes = open(os.path.join(ROOT, "targets", TARGET, "addon", "Classes", "TrainingNotes.lua"), encoding="utf-8").read()
quest_ids = {int(x) for x in re.findall(r"\[(\d+)\]\s*=\s*\"", notes)}

lines = ["# What's Training? data compared with the client tables: " + TARGET, "",
         "GENERATED by `tools/research/whatstraining_import.py` (upstream commit `" + COMMIT[:12] + "`, folder `Classes/" + GAME
         + "`; client build " + BUILD + "). Do not edit by hand.", "",
         "*Both*: spells in the client-table list (`Classes/TrainingData.lua`) that What's Training lists as sold by the class"
         " trainer. *Level differs*: same spell, different level. *Only What's Training*: trainer spells our client-table"
         " import leaves out (mostly level-1 spells and spells our rules drop). *Only client tables*: spells What's Training"
         " does not list as trainer spells; *quest* marks those our notes list as class-quest spells.", "",
         "| Class | Both | Level differs | Only What's Training | Only client tables | of which quest |", "|---|---|---|---|---|---|"]
detail = []
for cls in CLASSES:
    w, o = data[cls], ours.get(cls, {})
    both = [i for i in o if i in w]
    diff = [i for i in both if w[i][0] != o[i][0]]
    onlyw = [i for i in w if i not in o]
    onlyo = [i for i in o if i not in w]
    q = [i for i in onlyo if i in quest_ids]
    lines.append("| %s | %d | %d | %d | %d | %d |" % (cls, len(both), len(diff), len(onlyw), len(onlyo), len(q)))
    if diff:
        detail.append("- **%s, level differs:** %s" % (cls, ", ".join("%s %d (WT %d, client %d)" % (o[i][1], i, w[i][0], o[i][0]) for i in sorted(diff))))
    if onlyo:
        detail.append("- **%s, only client tables:** %s" % (cls, ", ".join("%s %d%s" % (o[i][1], i, " (quest)" if i in quest_ids else "") for i in sorted(onlyo))))
lines += ["", "## Details", ""] + (detail or ["None."]) + [""]
rep = os.path.join(ROOT, "docs", "generated", TARGET, "whatstraining-crosscheck.md")
with open(rep, "w", encoding="utf-8", newline="\n") as f:
    f.write("\n".join(lines))
print("%s: %d spells from Classes/%s; report %s" % (TARGET, sum(len(v) for v in data.values()), GAME, os.path.relpath(rep, ROOT)))
