// Input: TaxiNodes and TaxiPath (client DB2 CSV, tools/upstream.json), UiMapAssignment for the zone maps, and the
// bundled QuestieDB tables (Zones.lua, Npcs.lua) for zone ids and flight masters. Only on targets with
// target.json clientTables.flights = true.
// Output: <add-on>/Database/Flights.lua
//   nodes[id] = { name, full, zone, x, y, faction ("A", "H" or "AH"), npc }  (x, y in zone map percent)
//   links[id] = { ids of the nodes it has a direct flight to }
// Kept: nodes with a faction flag, at least one flight and a place on Eastern Kingdoms, Kalimdor or Outland. Left out:
// transports, zeppelin targets, scripted quest/PvP flights and teleports, and battleground nodes. Flight times are not in the client
// tables; Core/FlightTimer.lua measures them in game.

using System;
using System.Collections.Generic;
using System.Globalization;
using System.IO;
using System.Linq;
using System.Text;

namespace GuideTools
{
    public sealed class FlightNode
    {
        public int Id, Continent, Zone, Npc;
        public string Name, Full, Faction;
        public double WorldX, WorldY, X, Y;
        public List<int> Links = new List<int>();
    }

    public static class FlightTables
    {
        const double NpcMatch = 3.0; // map percent between a node and its flight master
        // Eastern Kingdoms, Kalimdor and Outland; battleground maps (Alterac Valley's nodes) are left out.
        static readonly HashSet<int> Continents = new HashSet<int> { 0, 1, 530 };
        // Scripted quest flights, PvP bombing runs and teleports share the taxi tables: "Quest Path 9571",
        // "Quest - Nethrandamus Start", "Nagrand - PvP - Attack Run Start 1", "Eversong - Duskwither Teleport".
        static readonly System.Text.RegularExpressions.Regex ScriptedFlight =
            new System.Text.RegularExpressions.Regex(@"\b(Quest|PvP|Teleport)\b");

        public static string Export(string db2Dir, string addOnDir, string build, List<string> report)
        {
            var db = BundledDb.Load(addOnDir);
            var nodes = Build(db2Dir, db, report);
            var sb = new StringBuilder();
            sb.Append("-- " + Ctx.Name + " - flight graph for " + Ctx.TargetName + " (src = client, v = 1)\n");
            sb.Append("-- GENERATED by tools/build.ps1 import-client from client TaxiNodes/TaxiPath (build " + build + "). DO NOT EDIT.\n");
            sb.Append("-- nodes[id] = { name, full, zone, x, y, faction (\"A\", \"H\", \"AH\"), npc (flight master id or nil) }; links[id] = { direct flights }\n");
            sb.Append("local _, ns = ...\n");
            sb.Append("ns.Flights = { build = " + LuaWriter.Str(build) + ", nodes = {}, links = {} }\n");
            sb.Append("local N, L = ns.Flights.nodes, ns.Flights.links\n");
            foreach (var n in nodes.Values.OrderBy(n => n.Id))
            {
                sb.Append("N[" + n.Id + "]={name=" + LuaWriter.Str(n.Name) + ",full=" + LuaWriter.Str(n.Full) + ",zone=" + n.Zone +
                          ",x=" + LuaWriter.Num(Math.Round(n.X, 1)) + ",y=" + LuaWriter.Num(Math.Round(n.Y, 1)) +
                          ",faction=" + LuaWriter.Str(n.Faction) + (n.Npc > 0 ? ",npc=" + n.Npc : "") + "}\n");
            }
            foreach (var n in nodes.Values.OrderBy(n => n.Id))
                sb.Append("L[" + n.Id + "]={" + string.Join(",", n.Links.OrderBy(i => i).Select(i => i.ToString(CultureInfo.InvariantCulture)).ToArray()) + "}\n");
            File.WriteAllText(Path.Combine(addOnDir, "Database", "Flights.lua"), sb.ToString(), new UTF8Encoding(false));
            int links = nodes.Values.Sum(n => n.Links.Count);
            int noNpc = nodes.Values.Count(n => n.Npc == 0);
            return "flight nodes: " + nodes.Count + ", flights: " + links + ", nodes without a flight master in the data: " + noNpc;
        }

        // Database/ZoneGeo.lua: for every zone map the bundled data knows, its continent and world bounding box, so
        // the add-on can place a zone-percent point in the world and compare distances across zones (Completionist
        // routing picks the nearest suitable zone). From UiMapAssignment's whole-map rows.
        public static string ExportZoneGeo(string db2Dir, string addOnDir, string build)
        {
            var db = BundledDb.Load(addOnDir);
            var zoneOfUi = new Dictionary<int, int>();
            foreach (var kv in db.UiMap) if (!zoneOfUi.ContainsKey(kv.Value)) zoneOfUi[kv.Value] = kv.Key;
            var sb = new StringBuilder();
            sb.Append("-- " + Ctx.Name + " - zone geography for " + Ctx.TargetName + " (src = client, v = 1)\n");
            sb.Append("-- GENERATED by tools/build.ps1 import-client from client UiMapAssignment (build " + build + "). DO NOT EDIT.\n");
            sb.Append("-- [zoneId] = { continent, minX, minY, maxX, maxY } in world yards; zone map x runs along -Y, y along -X.\n");
            sb.Append("local _, ns = ...\nns.ZoneGeo = {\n");
            var seen = new HashSet<int>();
            foreach (var r in Csv.Read(Path.Combine(db2Dir, "UiMapAssignment.csv")))
            {
                if (!(r["UiMin_0"] == "0" && r["UiMin_1"] == "0" && r["UiMax_0"] == "1" && r["UiMax_1"] == "1")) continue;
                int zone;
                if (!zoneOfUi.TryGetValue(Csv.I(r, "UiMapID"), out zone) || !seen.Add(zone)) continue;
                sb.Append("  [" + zone + "] = { " + Csv.I(r, "MapID") + ", " + LuaWriter.Num(Math.Round(D(r, "Region_0"), 1)) + ", " +
                          LuaWriter.Num(Math.Round(D(r, "Region_1"), 1)) + ", " + LuaWriter.Num(Math.Round(D(r, "Region_3"), 1)) + ", " +
                          LuaWriter.Num(Math.Round(D(r, "Region_4"), 1)) + " },\n");
            }
            sb.Append("}\n");
            File.WriteAllText(Path.Combine(addOnDir, "Database", "ZoneGeo.lua"), sb.ToString(), new UTF8Encoding(false));
            return "zone geography: " + seen.Count + " zones";
        }

        public static Dictionary<int, FlightNode> Build(string db2Dir, BundledDb db, List<string> report)
        {
            var paths = Csv.Read(Path.Combine(db2Dir, "TaxiPath.csv"));
            var hasPath = new HashSet<int>(paths.Select(p => Csv.I(p, "FromTaxiNode")));
            var nodes = new Dictionary<int, FlightNode>();
            foreach (var r in Csv.Read(Path.Combine(db2Dir, "TaxiNodes.csv")))
            {
                int id = Csv.I(r, "ID"), flags = Csv.I(r, "Flags"), cont = Csv.I(r, "ContinentID");
                string full = r["Name_lang"];
                if ((flags & 3) == 0 || !hasPath.Contains(id) || !Continents.Contains(cont)) continue;
                if (full.StartsWith("Transport", StringComparison.Ordinal) || ScriptedFlight.IsMatch(full)) continue;
                int comma = full.IndexOf(", ", StringComparison.Ordinal);
                nodes[id] = new FlightNode
                {
                    Id = id, Continent = cont, Full = full, Name = comma > 0 ? full.Substring(0, comma) : full,
                    Faction = (flags & 3) == 3 ? "AH" : ((flags & 1) != 0 ? "A" : "H"),
                    WorldX = D(r, "Pos_0"), WorldY = D(r, "Pos_1"),
                };
            }
            foreach (var p in paths)
            {
                FlightNode a, b;
                int to = Csv.I(p, "ToTaxiNode");
                if (nodes.TryGetValue(Csv.I(p, "FromTaxiNode"), out a) && nodes.TryGetValue(to, out b) && !a.Links.Contains(to)) a.Links.Add(to);
            }

            // Zone map boxes: the whole-map assignment of every zone map the bundled data knows.
            var zoneOfUi = new Dictionary<int, int>();
            foreach (var kv in db.UiMap) if (!zoneOfUi.ContainsKey(kv.Value)) zoneOfUi[kv.Value] = kv.Key;
            var boxes = new List<Tuple<int, int, double, double, double, double>>(); // zone, continent, minX, minY, maxX, maxY
            foreach (var r in Csv.Read(Path.Combine(db2Dir, "UiMapAssignment.csv")))
            {
                int ui = Csv.I(r, "UiMapID"), zone;
                if (!(r["UiMin_0"] == "0" && r["UiMin_1"] == "0" && r["UiMax_0"] == "1" && r["UiMax_1"] == "1")) continue;
                if (!zoneOfUi.TryGetValue(ui, out zone)) continue;
                boxes.Add(Tuple.Create(zone, Csv.I(r, "MapID"), D(r, "Region_0"), D(r, "Region_1"), D(r, "Region_3"), D(r, "Region_4")));
            }
            foreach (var n in nodes.Values)
            {
                // Zone maps are rectangles and overlap their neighbours, so every zone map that contains the node is
                // a candidate: the one with the node's flight master closest wins. Without a flight master in range,
                // the smallest containing map (a city before its zone) is used.
                var cands = boxes.Where(b => b.Item2 == n.Continent && n.WorldX >= b.Item3 && n.WorldX <= b.Item5 && n.WorldY >= b.Item4 && n.WorldY <= b.Item6)
                                 .OrderBy(b => (b.Item5 - b.Item3) * (b.Item6 - b.Item4)).ToList();
                if (cands.Count == 0) { report.Add("flight node " + n.Id + " " + n.Full + ": no zone map contains it"); continue; }
                double best = NpcMatch;
                foreach (var box in cands)
                {
                    double x = (box.Item6 - n.WorldY) / (box.Item6 - box.Item4) * 100, y = (box.Item5 - n.WorldX) / (box.Item5 - box.Item3) * 100;
                    if (n.Zone == 0) { n.Zone = box.Item1; n.X = x; n.Y = y; }
                    foreach (var kv in db.Npcs)
                    {
                        if ((BundledDb.Num(kv.Value, BundledDb.N_FLAGS) & Ctx.FlagFlight) == 0) continue;
                        string fr = BundledDb.Str(kv.Value, BundledDb.N_FRIENDLY) ?? "";
                        if (!n.Faction.All(c => fr.IndexOf(c) >= 0)) continue;
                        foreach (var sp in db.NpcSpawns(kv.Key))
                        {
                            if ((int)sp[0] != box.Item1) continue;
                            double d = Math.Sqrt((sp[1] - x) * (sp[1] - x) + (sp[2] - y) * (sp[2] - y));
                            if (d < best) { best = d; n.Npc = kv.Key; n.Zone = box.Item1; n.X = x; n.Y = y; }
                        }
                    }
                }
                if (n.Npc == 0) report.Add("flight node " + n.Id + " " + n.Full + " (" + n.Faction + "): no flight master within " + NpcMatch + "% (zone " + n.Zone + ")");
            }
            return nodes.Where(kv => kv.Value.Zone > 0).ToDictionary(kv => kv.Key, kv => kv.Value);
        }

        static double D(Dictionary<string, string> r, string k)
        {
            string v;
            double d;
            return r.TryGetValue(k, out v) && double.TryParse(v, NumberStyles.Float, CultureInfo.InvariantCulture, out d) ? d : 0;
        }
    }
}
