-- Questwarden - Completionist coverage matrix (not a test): classifies every quest in the staged target's data for
-- every race/class combination with the real planner (Core/Completionist.lua) and writes
-- docs/generated/<Target>/completionist-coverage.md. Run: tools/build.ps1 completionist-coverage -Target <Target>
-- SPDX-License-Identifier: GPL-3.0-only

dofile("tests/mock_wow.lua")
local STAGE = dofile("build/" .. assert(os.getenv("GUIDE_TARGET"), "set GUIDE_TARGET") .. "/stage.lua")
local ADDON, root = STAGE.name, STAGE.dir
local ns = {}
local function loadFile(path)
    local chunk = assert(loadfile(path))
    chunk(ADDON, ns)
end
local toc = assert(io.open(root .. (STAGE.toc or (ADDON .. ".toc")), "r"))
for line in toc:lines() do
    line = line:gsub("\r", "")
    if line ~= "" and not line:match("^#") then
        local rel = line:gsub("\\", "/")
        if rel:match("%.xml$") then
            local f = assert(io.open(root .. rel, "r"))
            local dir = root .. rel:match("^(.*/)")
            for file in string.gmatch(f:read("*a"), '<Script%s+file="([^"]+)"') do loadFile(dir .. file:gsub("\\", "/")) end
            f:close()
        else
            loadFile(root .. rel)
        end
    end
end
toc:close()
MOCK.fire("ADDON_LOADED", ADDON)
MOCK.fire("PLAYER_LOGIN")

local CM = ns.Completionist
local rows, total = {}, 0
for _ in pairs(ns.QDB.quests) do total = total + 1 end
local races = {}
for race, r in pairs(ns.RaceClass and ns.RaceClass.races or {}) do races[#races + 1] = { race, r } end
table.sort(races, function(a, b) return a[1] < b[1] end)
local COLS = { "routable", "ineligible", "raid", "group", "profession", "reputation", "event", "repeatable", "missing" }
for _, rr in ipairs(races) do
    local race, r = rr[1], rr[2]
    for _, class in ipairs(r.classes) do
        local ctx = { race = race, class = class, faction = r.faction, level = ns.Target.maxLevel,
                      completed = function() return false end, inLog = function() return false end }
        local inv = CM:Inventory(ctx)
        local c = inv.counts
        local routable = (c.actionable or 0) + (c.deferred or 0) + (c.blocked or 0)
        local row = { race .. " " .. class, r.faction, routable }
        for i = 2, #COLS do row[#row + 1] = c[COLS[i]] or 0 end
        rows[#rows + 1] = row
    end
end

local out = {
    "# Completionist coverage: " .. ns.Target.name, "",
    "GENERATED by `tools/build.ps1 completionist-coverage` (tests/completionist_coverage.lua) with the add-on's own planner",
    "(Core/Completionist.lua), for a level-" .. ns.Target.maxLevel .. " character with no quest done. Do not edit by hand.", "",
    "Quests in the bundled data: **" .. total .. "**. *Routable*: quests this character can take whose giver and finisher",
    "have positions (the Completionist route covers these), dungeon quests included: Completionist routes every dungeon.",
    "The other columns are counted but not routed by default (raid, group/elite, profession, reputation, event, repeatable;",
    "each can be turned on in setup or the settings),",
    "or cannot be: *ineligible* (other faction, race or class, or a maximum level) and *missing* (no giver or finisher position",
    "in the data). Quests the database does not have at all are not counted anywhere.", "",
    "| Character | Faction | Routable | Ineligible | Raid | Group | Profession | Reputation | Event | Repeatable | Missing data |",
    "|---|---|---|---|---|---|---|---|---|---|---|",
}
for _, r in ipairs(rows) do out[#out + 1] = "| " .. table.concat(r, " | ") .. " |" end
local path = "docs/generated/" .. STAGE.target .. "/completionist-coverage.md"
local f = assert(io.open(path, "w"))
f:write(table.concat(out, "\n") .. "\n")
f:close()
print("wrote " .. path .. " (" .. #rows .. " race/class combinations, " .. total .. " quests)")
